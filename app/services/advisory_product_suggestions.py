"""PR F / F2: the independent advisory product-suggestion worker (ADR-0014).

Runs on its own periodic task and its own Hub session. It never runs inside, before or
after classification, reclassification, matching, operator requests or accounting, and an
error here never reaches any of them. Per tick:

1. Hub only: the current PRODUCT_NOT_FOUND lines of pending reviews (the lines the child
   projection shows, with the effective commercial supplier of the persisted matching).
   Current sets whose line version is gone are superseded/invalidated.
2. No lines: done -- no Odoo call.
3. One bounded, read-only Odoo catalog snapshot. If it fails, nothing is regenerated or
   revalidated: persisted sets stay as they are and simply age out of display validity.
4. Per line (at most ``max_lines``, within ``budget_seconds``): an unchanged set is only
   revalidated; a missing or stale one is regenerated by the pure engine and the old set is
   superseded in the same commit. A failing line is rolled back and skipped.

``plan()`` computes the same outcome without any write (CLI dry-run).
"""

from __future__ import annotations

import logging
import time
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, field
from datetime import UTC, datetime
from enum import StrEnum
from typing import Protocol

from app.advisory.product_suggestions import (
    ENGINE_VERSION,
    CatalogSnapshot,
    PriorMapping,
    ProductSuggestionResult,
    SuggestionPolicy,
    suggest_products,
    supplierinfo_fingerprint,
    variant_catalog_fingerprint,
)
from app.advisory.suggestion_sets import (
    AdvisoryLine,
    StoredSuggestionSet,
    SuggestionSetReason,
    SuggestionSetStatus,
    replacement_reason,
    retirement,
)

logger = logging.getLogger(__name__)

MAX_LINES_PER_TICK = 200
TICK_BUDGET_SECONDS = 30.0


@dataclass(frozen=True, slots=True)
class HubLineSnapshot:
    lines: tuple[AdvisoryLine, ...]
    #: Every pending review of the company -> its current version.
    pending_versions: dict[str, int]


class AdvisoryLineSource(Protocol):
    def snapshot(self, *, company_id: int) -> HubLineSnapshot: ...


class PriorMappingSource(Protocol):
    def prior_mappings(self, *, company_id: int) -> tuple[PriorMapping, ...]: ...


class AdvisoryCatalogReader(Protocol):
    def read(self, *, company_id: int) -> CatalogSnapshot: ...


class SuggestionSetRepository(Protocol):
    def list_current(self, *, company_id: int) -> tuple[StoredSuggestionSet, ...]: ...

    def insert_current(
        self,
        line: AdvisoryLine,
        result: ProductSuggestionResult,
        *,
        catalog_fingerprint: str,
        supplierinfo_fingerprint: str,
        engine_version: str,
        now: datetime,
        product_names: Mapping[int, str] | None = None,
    ) -> int: ...

    def retire(
        self, set_id: int, *, status: SuggestionSetStatus, reason: SuggestionSetReason, now: datetime
    ) -> bool: ...

    def revalidate(self, set_ids: Sequence[int], *, now: datetime) -> int: ...


class AdvisoryTickStatus(StrEnum):
    COMPLETED = "completed"
    NO_LINES = "no_lines"
    CATALOG_FAILED = "catalog_failed"
    BUDGET_EXHAUSTED = "budget_exhausted"


class PlannedAction(StrEnum):
    GENERATE = "generate"
    REGENERATE = "regenerate"
    REVALIDATE = "revalidate"


@dataclass(frozen=True, slots=True)
class PlannedLine:
    line: AdvisoryLine
    action: PlannedAction
    reason: SuggestionSetReason | None
    result: ProductSuggestionResult | None


@dataclass(frozen=True, slots=True)
class PlannedRetirement:
    stored: StoredSuggestionSet
    status: SuggestionSetStatus
    reason: SuggestionSetReason


@dataclass(frozen=True, slots=True)
class AdvisoryPlan:
    status: AdvisoryTickStatus
    retirements: tuple[PlannedRetirement, ...] = ()
    lines: tuple[PlannedLine, ...] = ()
    lines_seen: int = 0
    truncated: int = 0
    catalog_error: str | None = None


@dataclass(frozen=True, slots=True)
class AdvisoryTickResult:
    status: AdvisoryTickStatus
    lines_seen: int = 0
    generated: int = 0
    revalidated: int = 0
    retired: int = 0
    failed_lines: int = 0
    truncated: int = 0
    errors: tuple[str, ...] = field(default_factory=tuple)


class AdvisoryProductSuggestionService:
    def __init__(
        self,
        *,
        line_source: AdvisoryLineSource,
        prior_source: PriorMappingSource,
        catalog_reader: AdvisoryCatalogReader,
        repository: SuggestionSetRepository,
        commit: Callable[[], None],
        rollback: Callable[[], None],
        policy: SuggestionPolicy | None = None,
        clock: Callable[[], datetime] = lambda: datetime.now(UTC),
        monotonic: Callable[[], float] = time.monotonic,
        max_lines: int = MAX_LINES_PER_TICK,
        budget_seconds: float = TICK_BUDGET_SECONDS,
    ) -> None:
        self._line_source = line_source
        self._prior_source = prior_source
        self._catalog_reader = catalog_reader
        self._repository = repository
        self._commit = commit
        self._rollback = rollback
        self._policy = policy
        self._clock = clock
        self._monotonic = monotonic
        self._max_lines = max_lines
        self._budget_seconds = budget_seconds

    # ------------------------------------------------------------------ dry run

    def plan(self, *, company_id: int) -> AdvisoryPlan:
        """The tick's outcome without any Hub or Odoo write."""

        snapshot = self._line_source.snapshot(company_id=company_id)
        current = {stored.key: stored for stored in self._repository.list_current(company_id=company_id)}
        retirements = _retirements(snapshot, current)
        if not snapshot.lines:
            return AdvisoryPlan(status=AdvisoryTickStatus.NO_LINES, retirements=retirements)
        try:
            catalog = self._catalog_reader.read(company_id=company_id)
        except Exception as exc:  # noqa: BLE001 - reported, never raised into a workflow
            return AdvisoryPlan(
                status=AdvisoryTickStatus.CATALOG_FAILED,
                retirements=retirements,
                lines_seen=len(snapshot.lines),
                catalog_error=_safe(exc),
            )
        priors = self._priors(company_id)
        variant_fp, supplierinfo_fp = variant_catalog_fingerprint(catalog), supplierinfo_fingerprint(catalog)
        work = snapshot.lines[: self._max_lines]
        planned = []
        for line in work:
            existing = current.get(line.key)
            reason = (
                replacement_reason(
                    existing, line, catalog_fingerprint=variant_fp, supplierinfo_fingerprint=supplierinfo_fp
                )
                if existing is not None
                else None
            )
            if existing is not None and reason is None:
                planned.append(PlannedLine(line, PlannedAction.REVALIDATE, None, existing.result))
                continue
            result = suggest_products(line.suggestion_line(), catalog, prior_mappings=priors, policy=self._policy)
            action = PlannedAction.REGENERATE if existing is not None else PlannedAction.GENERATE
            planned.append(PlannedLine(line, action, reason, result))
        return AdvisoryPlan(
            status=AdvisoryTickStatus.COMPLETED,
            retirements=retirements,
            lines=tuple(planned),
            lines_seen=len(snapshot.lines),
            truncated=len(snapshot.lines) - len(work),
        )

    # ------------------------------------------------------------------ tick

    def run(self, *, company_id: int) -> AdvisoryTickResult:
        started = self._monotonic()
        now = self._clock()
        if now.tzinfo is None:
            raise ValueError("clock must return a timezone-aware datetime.")
        snapshot = self._line_source.snapshot(company_id=company_id)
        current = {stored.key: stored for stored in self._repository.list_current(company_id=company_id)}

        retired = 0
        for planned in _retirements(snapshot, current):
            if self._repository.retire(planned.stored.id, status=planned.status, reason=planned.reason, now=now):
                retired += 1
        self._commit()

        if not snapshot.lines:
            logger.info("advisory.product_suggestions.no_lines", extra={"company_id": company_id, "retired": retired})
            return AdvisoryTickResult(status=AdvisoryTickStatus.NO_LINES, retired=retired)

        try:
            catalog = self._catalog_reader.read(company_id=company_id)
        except Exception as exc:  # noqa: BLE001 - advisory failure never reaches a workflow
            logger.warning(
                "advisory.product_suggestions.catalog_failed",
                extra={"company_id": company_id, "error_type": exc.__class__.__name__},
            )
            return AdvisoryTickResult(
                status=AdvisoryTickStatus.CATALOG_FAILED,
                lines_seen=len(snapshot.lines),
                retired=retired,
                errors=(_safe(exc),),
            )

        priors = self._priors(company_id)
        variant_fp, supplierinfo_fp = variant_catalog_fingerprint(catalog), supplierinfo_fingerprint(catalog)
        # F3.1: the display name snapshot comes from the same read the fingerprint covers, so a
        # renamed product changes the fingerprint and regenerates the set (never a stale name).
        product_names = {variant.product_id: variant.name for variant in catalog.variants}
        work = snapshot.lines[: self._max_lines]
        truncated = len(snapshot.lines) - len(work)
        generated = failed = 0
        unchanged: list[int] = []
        status = AdvisoryTickStatus.COMPLETED
        for line in work:
            if self._monotonic() - started > self._budget_seconds:
                status = AdvisoryTickStatus.BUDGET_EXHAUSTED
                break
            existing = current.get(line.key)
            reason = (
                replacement_reason(
                    existing, line, catalog_fingerprint=variant_fp, supplierinfo_fingerprint=supplierinfo_fp
                )
                if existing is not None
                else None
            )
            if existing is not None and reason is None:
                unchanged.append(existing.id)
                continue
            try:
                result = suggest_products(line.suggestion_line(), catalog, prior_mappings=priors, policy=self._policy)
                if existing is not None and reason is not None:
                    self._repository.retire(existing.id, status=SuggestionSetStatus.SUPERSEDED, reason=reason, now=now)
                self._repository.insert_current(
                    line,
                    result,
                    catalog_fingerprint=variant_fp,
                    supplierinfo_fingerprint=supplierinfo_fp,
                    engine_version=ENGINE_VERSION,
                    now=now,
                    product_names=product_names,
                )
                self._commit()
                generated += 1
            except Exception as exc:  # noqa: BLE001 - one line never stops the tick
                self._rollback()
                failed += 1
                logger.warning(
                    "advisory.product_suggestions.line_failed",
                    extra={
                        "review_id": line.review_id,
                        "line_number": line.line_number,
                        "error_type": type(exc).__name__,
                    },
                )
        revalidated = self._repository.revalidate(unchanged, now=now) if unchanged else 0
        self._commit()
        if truncated:
            logger.info(
                "advisory.product_suggestions.truncated", extra={"company_id": company_id, "skipped": truncated}
            )
        return AdvisoryTickResult(
            status=status,
            lines_seen=len(snapshot.lines),
            generated=generated,
            revalidated=revalidated,
            retired=retired,
            failed_lines=failed,
            truncated=truncated,
        )

    def _priors(self, company_id: int) -> tuple[PriorMapping, ...]:
        try:
            return self._prior_source.prior_mappings(company_id=company_id)
        except Exception as exc:  # noqa: BLE001 - T2 is optional; the other tiers still run
            logger.warning(
                "advisory.product_suggestions.history_unavailable",
                extra={"company_id": company_id, "error_type": exc.__class__.__name__},
            )
            return ()


def _retirements(
    snapshot: HubLineSnapshot, current: dict[tuple[str, int, str], StoredSuggestionSet]
) -> tuple[PlannedRetirement, ...]:
    live = {line.key for line in snapshot.lines}
    planned = []
    for key in sorted(current):
        if key in live:
            continue
        stored = current[key]
        status, reason = retirement(stored, pending_versions=snapshot.pending_versions)
        planned.append(PlannedRetirement(stored=stored, status=status, reason=reason))
    return tuple(planned)


def _safe(exc: Exception) -> str:
    message = getattr(exc, "safe_message", None)
    return f"{exc.__class__.__name__}: {message}" if isinstance(message, str) else exc.__class__.__name__


